export const dictionaries: Record<Language, Dictionary> = { id, en };

// Turns a stored "YYYY-MM" value into a label such as "Jan 2024".
export function formatMonth(value: string, language: Language): string {
  const match = /^(\d{4})-(\d{2})$/.exec(value);
  if (!match) return value;
  const month = dictionaries[language].months[Number(match[2]) - 1];
  return month ? `${month} ${match[1]}` : value;
}

export function formatRange(start: string, end: string, current: boolean, language: Language): string {
  const endLabel = current ? dictionaries[language].present : formatMonth(end, language);
  return [formatMonth(start, language), endLabel].filter(Boolean).join(" - ");
}
